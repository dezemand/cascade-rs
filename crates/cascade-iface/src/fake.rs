/// VAG-style slow-init epilog (upstream notes it is "massively broken").
const AUDI_EPILOG: &[u8] = &[
    0x0f, 0xf0, 0x01, 0xfe, 0xf6, 0x09, 0x30, 0xcf, 0x33, 0xcc, 0x30, 0xcf, 0x39, 0xc6, 0x30, 0xcf,
    0x36, 0xc9, 0x30, 0xcf, 0x33, 0xcc, 0x32, 0xcd, 0x45, 0xba, 0x20, 0xdf, 0x20, 0xdf, 0x03,
];

/// Upstream's fixed-size request buffers (`int obd_message[128]` etc.).
const MSG_CAP: usize = 128;

pub struct Fake {
    state: State,
    delay: Cycles,
    obd_message: Vec<u8>,
    obd_request: Vec<u8>,
    reply_cycle: u32,
    slow_init_target: u8,
    baud_divisor: u32,
    hyundai: bool,
    can_mode: u8,
    can_length: usize,
    can_message: Vec<u8>,
    /// Set if the firmware overran a request buffer, which is undefined
    /// behaviour upstream. Excess bytes are dropped here.
    pub overflow: bool,
}

impl Default for Fake {
    fn default() -> Self {
        Self {
            state: State::Idle,
            delay: 0,
            obd_message: Vec::new(),
            obd_request: Vec::new(),
            reply_cycle: 0,
            slow_init_target: 0,
            baud_divisor: 0,
            hyundai: true,
            can_mode: 0,
            can_length: 0,
            can_message: Vec::new(),
            overflow: false,
        }
    }
}

impl Fake {
    /// Upstream `get_obd_reply`: entries whose request is a prefix of the
    /// message match; several matches rotate; no match gives no reply.
    fn obd_reply(&mut self, msg: &[u8]) -> &'static [u8] {
        let matches: Vec<&'static [u8]> = OBD_REPLIES
            .iter()
            .filter(|(req, _)| msg.starts_with(req))
            .map(|(_, rep)| *rep)
            .take(10)
            .collect();
        match matches.len() {
            0 => &[],
            1 => matches[0],
            n => {
                let r = matches[(self.reply_cycle % n as u32) as usize];
                self.reply_cycle = self.reply_cycle.wrapping_add(1);
                r
            }
        }
    }

    fn push_capped(buf: &mut Vec<u8>, cap: usize, byte: u8, overflow: &mut bool) {
        if buf.len() < cap {
            buf.push(byte);
        } else {
            *overflow = true;
        }
    }
}

impl Interface for Fake {
    fn set_baud_divisor(&mut self, _now: Cycles, divisor: u32, rx: &mut dyn RxBuf) {
        if self.baud_divisor != divisor {
            self.baud_divisor = divisor;
            rx.flush();
        }
    }

    fn send_byte(&mut self, now: Cycles, byte: u8, rx: &mut dyn RxBuf) {
        let bd = self.baud_divisor;
        let quiet = now + 8 * bd as u64 * 10 * 2;
        match self.state {
            State::Idle if bd == 0x77 || bd == 0x76 || bd == 0x81 => {
                self.state = State::ObdComposing;
                self.obd_message.clear();
                self.obd_message.push(byte);
                self.delay = quiet;
            }
            State::ObdComposing => {
                // upstream writes a -1 terminator after the last OBD byte
                Self::push_capped(&mut self.obd_message, MSG_CAP - 1, byte, &mut self.overflow);
                self.delay = quiet;
            }
            State::SlowInitWaitForCheckByte => {
                self.state = State::SlowInitCheckByteReceived;
                self.delay = now + 1000;
            }
            State::Idle if byte == 0xf1 => {
                self.state = State::CanStart;
                self.can_message.clear();
                rx.flush();
            }
            State::CanStart => {
                self.can_mode = byte;
                self.state = State::CanLength;
            }
            State::CanLength => {
                self.can_length = byte as usize;
                self.state = if self.can_length == 0 {
                    State::CanAnswering
                } else {
                    State::CanComposing
                };
            }
            State::CanComposing => {
                Self::push_capped(&mut self.can_message, MSG_CAP, byte, &mut self.overflow);
                if self.can_message.len() == self.can_length {
                    self.state = State::CanAnswering;
                }
            }
            _ => {}
        }
    }

    fn send_slow_init(&mut self, now: Cycles, target: u8, _rx: &mut dyn RxBuf) {
        self.state = State::SlowInitKwSent;
        // 100 ms reply delay plus 200 ms for the last init bit
        self.delay = now + 100 * 10000 + 200 * 10000;
        self.slow_init_target = target;
        self.hyundai = target >= 0x30;
    }

    fn poll_input(&mut self, now: Cycles, rx: &mut dyn RxBuf) {
        if now < self.delay {
            return;
        }
        match self.state {
            State::ObdComposing => {
                self.state = State::ObdAnswering;
                self.delay = now + 3000;
                self.obd_request = std::mem::take(&mut self.obd_message);
            }
            State::ObdAnswering => {
                let req = std::mem::take(&mut self.obd_request);
                for &b in self.obd_reply(&req) {
                    rx.push(b);
                }
                self.state = State::Idle;
            }
            State::SlowInitKwSent => {
                rx.push(0x55);
                self.state = State::SlowInitPauseAfter55;
                self.delay = now + 6 * 10000;
            }
            State::SlowInitPauseAfter55 => {
                let kw: &[u8] = if self.hyundai {
                    &[0x08, 0x08]
                } else {
                    &[0x01, 0x8a]
                };
                for &b in kw {
                    rx.push(b);
                }
                self.state = State::SlowInitWaitForCheckByte;
            }
            State::SlowInitCheckByteReceived => {
                if self.hyundai {
                    rx.push(!self.slow_init_target);
                } else {
                    for &b in AUDI_EPILOG {
                        rx.push(b);
                    }
                }
                self.state = State::Idle;
            }
            State::CanAnswering => {
                let mut reply = [0u8; 14];
                reply[..4].copy_from_slice(&[0x42, 0xf2, 0xff, 0]);
                let len = match self.can_mode {
                    0xfa => {
                        reply[2] = 0xf6;
                        4
                    }
                    0xfb => {
                        reply[2..8].copy_from_slice(&[0xfc, 10, 0xfc, 0xe0, 0x70, 1]);
                        14
                    }
                    0xfc => {
                        reply[2..9].copy_from_slice(&[0xfc, 10, 0xfc, 0xe0, 0x60, 1, 0x50]);
                        14
                    }
                    _ => 4,
                };
                for &b in &reply[..len] {
                    rx.push(b);
                }
                self.state = State::Idle;
            }
            _ => {}
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hyundai_slow_init_sequence() {
        let mut f = Fake::default();
        let mut rx: Vec<u8> = Vec::new();
        f.send_slow_init(1000, 0x33, &mut rx);
        f.poll_input(1000, &mut rx);
        assert!(rx.is_empty(), "no reply before the delay");
        let t = 1000 + 3_000_000;
        f.poll_input(t, &mut rx);
        assert_eq!(rx, [0x55]);
        f.poll_input(t + 60_000, &mut rx);
        assert_eq!(rx, [0x55, 0x08, 0x08]);
        f.send_byte(t + 70_000, 0xf7, &mut rx); // tester's inverted KB2
        f.poll_input(t + 71_000, &mut rx);
        assert_eq!(rx, [0x55, 0x08, 0x08, 0xcc]); // inverted address
    }

    #[test]
    fn obd_request_gets_table_reply() {
        let mut f = Fake::default();
        let mut rx: Vec<u8> = Vec::new();
        f.set_baud_divisor(0, 0x77, &mut rx);
        let req = [0x68, 0x6a, 0xf1, 0x01, 0x01, 0xc5];
        let mut now = 100;
        for b in req {
            f.send_byte(now, b, &mut rx);
            now += 100;
        }
        let quiet = now + 8 * 0x77 * 10 * 2;
        f.poll_input(quiet, &mut rx); // message complete
        f.poll_input(quiet + 3000, &mut rx); // reply
        assert_eq!(
            rx,
            [0x48, 0x6b, 0x12, 0x41, 0x01, 0x01, 0x04, 0x00, 0x00, 0x0c]
        );
    }

    #[test]
    fn duplicate_entries_rotate() {
        let mut f = Fake::default();
        let req = [0x20, 0x05, 0x10, 0x10, 0xbb];
        let a = f.obd_reply(&req)[9];
        let b = f.obd_reply(&req)[9];
        assert_eq!((a, b), (0x95, 0x96));
    }

    #[test]
    fn can_frame_answered() {
        let mut f = Fake::default();
        let mut rx: Vec<u8> = vec![1, 2];
        for b in [0xf1, 0xfa, 0x00] {
            f.send_byte(0, b, &mut rx);
        }
        assert!(rx.is_empty(), "F1 flushes the receive buffer");
        f.poll_input(0, &mut rx);
        assert_eq!(rx, [0x42, 0xf2, 0xf6, 0x00]);
    }
}
