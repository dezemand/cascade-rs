//! Canned ECU, port of upstream `iface_fake.cpp`.
//!
//! Answers 5-baud slow init (Hyundai keyword 08 08, or a VAG-style reply
//! for targets below 0x30), a fixed table of ISO 9141 / OBD requests, and the
//! K+CAN dongle framing (`F1 mode len data`). Timing is in emulated cycles,
//! so it is deterministic, as upstream's is.
//!
//! One assumption: upstream never initialises `baud_divisor`; this port
//! starts it at 0. It only decides whether the first baud change flushes
//! the receive buffer and whether bytes sent before any baud change start
//! an OBD message.

